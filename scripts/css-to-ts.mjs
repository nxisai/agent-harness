/**
 * Compiled Tailwind → a TypeScript string constant.
 *
 * The UI renders into a shadow root, so its stylesheet has to be injected
 * there rather than linked from the document — a <link> in the host page's
 * head never crosses the boundary. Shipping the CSS as a string means a
 * consumer needs no Tailwind, no PostCSS and no bundler plugin: they import a
 * component and it arrives styled.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(resolve(root, '.tw/agent.css'), 'utf8');
const out = resolve(root, 'src/ui/tailwind.generated.ts');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `/* GENERATED by scripts/css-to-ts.mjs — do not edit. Source: src/ui/agent.tw.css */\n` +
    `export const TAILWIND_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`[agent-harness] tailwind → src/ui/tailwind.generated.ts (${css.length} chars)`);
